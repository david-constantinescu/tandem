SAMPLES = {
    "colosseum-ticket": ("Colosseum tour e-ticket.pdf", "application/pdf",
                         "A tour ticket that overlaps your Vatican visit — watch the conflict appear."),
    "lunch-screenshot": ("Osteria booking screenshot.png", "image/png",
                         "A restaurant booking screenshot (read with OCR or vision AI)."),
    "lisbon-email": ("Lisbon hotel confirmation.eml", "message/rfc822",
                     "A hotel email for a different trip — Tandem proposes a new trip."),
}


def build_sample(key: str, start: date, to: str) -> tuple[str, str, bytes]:
    filename, mime, _ = SAMPLES[key]
    data = {"colosseum-ticket": lambda: sample_colosseum_ticket(start),
            "lunch-screenshot": lambda: sample_lunch_screenshot(start),
            "lisbon-email": lambda: sample_lisbon_email(start, to)}[key]()
    return filename, mime, data
