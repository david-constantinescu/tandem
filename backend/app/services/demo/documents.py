def _d(day: date) -> str:
    return day.strftime("%a %d %b %Y").replace(" 0", " ")


def make_pdf(title: str, subtitle: str, rows: list[tuple[str, str]], notes: list[str] | None = None,
             brand: str = "") -> bytes:
    import fitz

    doc = fitz.open()
    page = doc.new_page(width=595, height=842)
    page.draw_rect(fitz.Rect(0, 0, 595, 92), color=None, fill=(0.11, 0.23, 0.27))
    page.insert_text((40, 42), brand or title, fontname="hebo", fontsize=20, color=(1, 1, 1))
    page.insert_text((40, 68), subtitle, fontname="helv", fontsize=11, color=(0.85, 0.92, 0.92))
    y = 130
    page.insert_text((40, y), title, fontname="hebo", fontsize=15, color=(0.1, 0.1, 0.1))
    y += 30
    for label, value in rows:
        if label == "---":
            y += 8
            page.draw_line((40, y), (555, y), color=(0.85, 0.85, 0.85))
            y += 22
            continue
        page.insert_text((40, y), f"{label}:", fontname="hebo", fontsize=10.5, color=(0.35, 0.35, 0.35))
        page.insert_text((200, y), value, fontname="helv", fontsize=10.5, color=(0.08, 0.08, 0.08))
        y += 20
    for note in notes or []:
        y += 8
        rect = fitz.Rect(40, y, 555, y + 40)
        page.insert_textbox(rect, note, fontname="helv", fontsize=9.5, color=(0.3, 0.3, 0.3))
        y += 34
    page.insert_text((40, 815), DEMO_FOOTER, fontname="helv", fontsize=8, color=(0.6, 0.2, 0.2))
    return doc.tobytes()


def make_png(header: str, lines: list[str]) -> bytes:
    from PIL import Image, ImageDraw

    width, line_h = 1080, 46
    height = 220 + line_h * len(lines)
    img = Image.new("RGB", (width, height), (250, 250, 248))
    draw = ImageDraw.Draw(img)
    font = _font(30)
    bold = _font(38)
    draw.rectangle([0, 0, width, 120], fill=(24, 58, 66))
    draw.text((48, 38), header, fill=(255, 255, 255), font=bold)
    y = 160
    for line in lines:
        draw.text((48, y), line, fill=(20, 20, 20), font=font)
        y += line_h
    draw.text((48, height - 44), DEMO_FOOTER, fill=(150, 50, 50), font=_font(20))
    out = io.BytesIO()
    img.save(out, format="PNG")
    return out.getvalue()


def _font(size: int):
    from PIL import ImageFont

    for path in ("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf", "/System/Library/Fonts/Supplemental/Arial.ttf",
                 "/Library/Fonts/Arial.ttf", "/System/Library/Fonts/Helvetica.ttc"):
        try:
            return ImageFont.truetype(path, size)
        except OSError:
            continue
    return ImageFont.load_default(size=size)


def make_eml(subject: str, sender: str, to: str, body: str, sent: datetime | None = None,
             attachments: list[tuple[str, str, bytes]] | None = None) -> bytes:
    msg = EmailMessage()
    msg["Subject"] = subject
    msg["From"] = sender
    msg["To"] = to
    msg["Date"] = format_datetime(sent or datetime.now(timezone.utc))
    msg.set_content(body + "\n\n" + DEMO_FOOTER)
    for filename, mime, data in attachments or []:
        maintype, subtype = mime.split("/", 1)
        msg.add_attachment(data, maintype=maintype, subtype=subtype, filename=filename)
    return bytes(msg)


